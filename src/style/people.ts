/*
  OVERWORLD PEOPLE (16x16), drawn to Gold/Silver's proportions:
    - head rows 0-9: a wide hat/hair over a narrow face, eyes 2 px apart (columns 6 and 9)
    - body rows 10-15: about 10 px wide from the front with the hands at the sides,
      about 7 px wide from the side with a single leg showing
    - walking frames drop the whole sprite 1 px (the little bob) and swing one arm and leg
  Like the GBC, each person has 3 colors + transparent:
    '.' transparent   '1' skin   '2' clothing/hat color   '3' outline/hair
  A person = a head style + a body style + a clothing color (see LOOKS at the bottom).
  Side views face left; facing right is the mirror image.
*/

